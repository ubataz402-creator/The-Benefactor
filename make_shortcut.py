def find_pythonw():
    """pythonw.exe runs the app without a console window."""
    folder = os.path.dirname(sys.executable)
    cand = os.path.join(folder, "pythonw.exe")
    return cand if os.path.exists(cand) else sys.executable


def ps_quote(text):
    return "'" + text.replace("'", "''") + "'"


def powershell(script):
    return subprocess.run(
        ["powershell", "-NoProfile", "-NonInteractive", "-Command", script],
        check=True, capture_output=True, text=True,
    ).stdout.strip()


def make_shortcut(lnk_path):
    script = (
        "$s=(New-Object -ComObject WScript.Shell).CreateShortcut(" + ps_quote(lnk_path) + ");"
        "$s.TargetPath=" + ps_quote(find_pythonw()) + ";"
        "$s.Arguments=" + ps_quote('"' + APP + '"') + ";"
        "$s.WorkingDirectory=" + ps_quote(HERE) + ";"
        "$s.IconLocation=" + ps_quote(ICO + ",0") + ";"
        "$s.Description=" + ps_quote(NAME) + ";"
        "$s.Save()"
    )
    powershell(script)


def main():
    ap = argparse.ArgumentParser(description="Create a shortcut with the logo icon")
    ap.add_argument("--desktop", action="store_true", help="also create one on the Desktop")
    args = ap.parse_args()

    if os.name != "nt":
        print("This makes a Windows shortcut, so it only works on Windows.")
        return 1
    if not os.path.exists(APP):
        print("Couldn't find launder_app.pyw. Put this script in the same folder as it.")
        return 1

    with open(ICO, "wb") as f:
        f.write(base64.b64decode(ICO_B64))

    targets = [os.path.join(HERE, NAME + ".lnk")]
    if args.desktop:
        targets.append(os.path.join(powershell("[Environment]::GetFolderPath('Desktop')"), NAME + ".lnk"))
    try:
        for t in targets:
            make_shortcut(t)
            print("Created:", t)
    except (subprocess.CalledProcessError, OSError) as e:
        print("Couldn't create the shortcut:", getattr(e, "stderr", None) or e)
        return 1
    print("\nDone. Open the app with the new shortcut (it shows the logo).")
    return 0


if __name__ == "__main__":
    code = main()
    if sys.stdin and sys.stdin.isatty():
        input("\nPress Enter to close...")
    sys.exit(code)
